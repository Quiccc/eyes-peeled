/** Fill `{name}` placeholders. */
function fill(template: string, params?: Record<string, string | number>) {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in params ? String(params[name]) : whole));
}

/**
 * `english` in `locale` (the current request's by default), with placeholders filled. Unknown
 * messages and English come back as given.
 */
export function translate(english: string, params?: Record<string, string | number>, locale = currentLocale()): string {
  const translated = locale === 'en' ? undefined : MESSAGES[english]?.[locale];
  return fill(translated ?? english, params);
}

/** Whether `english` has translations (for tests). */
export function isTranslated(english: string): boolean {
  return english in MESSAGES;
}
